# -*- coding: utf-8 -*-
"""
模拟校园数据与三目标函数定义
项目：校园新增食堂选址 —— MOEA/D 学习项目
阶段：第一阶段（问题建模与可行性验证），不含任何进化算法。

运行环境：numpy 即可，无其他依赖。
"""

import numpy as np

# =====================================================================
# 1. 校园二维范围（米），坐标原点在西南角
# =====================================================================
CAMPUS_X = (0.0, 1000.0)
CAMPUS_Y = (0.0, 700.0)

# =====================================================================
# 2. 宿舍（需求点，全部等权）
#    布局意图：两个大型生活区（西 6 栋、东 6 栋）+ 一个小型生活区（北 4 栋）
# =====================================================================
DORMITORIES = np.array(
    [
        # --- 西生活区（6 栋） ---
        [185.0, 250.0],
        [240.0, 320.0],
        [155.0, 375.0],
        [280.0, 235.0],
        [255.0, 400.0],
        [200.0, 310.0],
        # --- 东生活区（6 栋） ---
        [770.0, 275.0],
        [825.0, 340.0],
        [745.0, 385.0],
        [805.0, 245.0],
        [715.0, 320.0],
        [775.0, 405.0],
        # --- 北生活区（4 栋） ---
        [480.0, 575.0],
        [535.0, 620.0],
        [445.0, 625.0],
        [520.0, 560.0],
    ]
)
N_DORM = len(DORMITORIES)

# =====================================================================
# 3. 已有食堂（f2 的竞争参考点）
#    布局意图：现实中的食堂总是建在生活区内部或边缘主干道旁，
#    因此每个食堂都靠近某一宿舍群，但不与该群质心严格重合。
# =====================================================================
EXISTING_CANTEENS = np.array(
    [
        [245.0, 295.0],  # C1：西生活区内，稍偏东南
        [755.0, 315.0],  # C2：东生活区内，稍偏西
        [500.0, 545.0],  # C3：北生活区南缘主干道旁
    ]
)
N_CANTEEN = len(EXISTING_CANTEENS)

# =====================================================================
# 4. 土地成本场参数（人为构造，单位：万元）
#    f3(x,y) = COST_BASE + Σ_k A_k · exp(-‖X-P_k‖² / (2 s_k²))
#    两个高成本"热点"分别模拟：教学行政核心区、东南滨水景观区。
# =====================================================================
COST_BASE = 80.0  # 基准土地成本（校园边缘空地）
COST_HOTSPOTS = [
    # (中心 cx, cy, 峰值增量 A, 影响半径 σ)
    (500.0, 350.0, 240.0, 160.0),  # 教学行政核心区（校园几何中心）
    (880.0, 110.0, 170.0, 100.0),  # 东南滨水景观区
]

# f2 中食堂的"服务半径"参数（米）：高斯服务场的标准差
SERVICE_RADIUS = 150.0


# =====================================================================
# 5. 目标函数（全部最小化）
# =====================================================================
def f1_avg_distance(x: float, y: float) -> float:
    """f1：全体宿舍到候选位置 (x,y) 的平均欧氏距离（米）。

    现实含义：新食堂对全校学生的整体可达性。
    输入：标量坐标；输出：非负实数（米）。
    """
    d = np.hypot(DORMITORIES[:, 0] - x, DORMITORIES[:, 1] - y)
    return float(d.mean())


def f2_competition(x: float, y: float) -> float:
    """f2：候选位置与已有食堂的服务范围重叠度（无量纲，[0,1]）。

    定义：f2 = (1/m) Σ_j exp( -‖X-C_j‖² / (2 σ²) )
    其中 σ = SERVICE_RADIUS，C_j 为已有食堂。
    现实含义：每个已有食堂有一个以 σ 为特征半径的高斯服务场，
    f2 度量新位置被已有食堂服务场"覆盖"的平均强度——
    新食堂若建在已有食堂服务场核心区，将与后者直接抢夺客流。
    输入：标量坐标；输出：[0,1]，越大竞争越激烈。
    """
    d2 = ((EXISTING_CANTEENS[:, 0] - x) ** 2) + ((EXISTING_CANTEENS[:, 1] - y) ** 2)
    return float(np.exp(-d2 / (2.0 * SERVICE_RADIUS**2)).mean())


def f3_land_cost(x: float, y: float) -> float:
    """f3：候选位置的土地/建设成本（万元）。

    定义：f3 = COST_BASE + Σ_k A_k · exp(-‖X-P_k‖² / (2 s_k²))
    现实含义：核心地段（行政教学区、景观区）土地机会成本高，
    边缘空地便宜。连续高斯场是对"分区地价"的光滑近似。
    输入：标量坐标；输出：≥ COST_BASE 的正实数（万元）。
    """
    c = COST_BASE
    for cx, cy, A, s in COST_HOTSPOTS:
        c += A * np.exp(-(((x - cx) ** 2) + ((y - cy) ** 2)) / (2.0 * s**2))
    return float(c)


def evaluate(X: np.ndarray) -> np.ndarray:
    """批量计算三目标。输入 (N,2) 坐标数组，返回 (N,3) 目标值矩阵 [f1,f2,f3]。"""
    X = np.atleast_2d(np.asarray(X, dtype=float))
    x, y = X[:, 0], X[:, 1]

    # f1：宿舍距离均值（向量化：(16,N)）
    dx = DORMITORIES[:, None, 0] - x[None, :]
    dy = DORMITORIES[:, None, 1] - y[None, :]
    f1 = np.hypot(dx, dy).mean(axis=0)

    # f2：与已有食堂的高斯重叠均值（(3,N)）
    cx = EXISTING_CANTEENS[:, None, 0] - x[None, :]
    cy = EXISTING_CANTEENS[:, None, 1] - y[None, :]
    d2 = cx**2 + cy**2
    f2 = np.exp(-d2 / (2.0 * SERVICE_RADIUS**2)).mean(axis=0)

    # f3：土地成本场
    f3 = np.full(X.shape[0], COST_BASE)
    for hcx, hcy, A, s in COST_HOTSPOTS:
        f3 = f3 + A * np.exp(-(((x - hcx) ** 2) + ((y - hcy) ** 2)) / (2.0 * s**2))

    return np.column_stack([f1, f2, f3])


def in_campus(x: float, y: float) -> bool:
    """边界约束：位置必须落在校园范围内。"""
    return CAMPUS_X[0] <= x <= CAMPUS_X[1] and CAMPUS_Y[0] <= y <= CAMPUS_Y[1]
